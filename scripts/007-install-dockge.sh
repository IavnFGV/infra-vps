#!/usr/bin/env bash
set -euo pipefail

# Dockge (stack manager UI, localhost only) from our own image:
# dockge/image/Dockerfile = louislam/dockge:1 + Debian/Docker security fixes,
# rebuilt on every run. Idempotent; the infra deploy re-runs it when Dockge is
# installed, so Dockge gets fixes with every deploy and the weekly rebuild.
# DOCKGE_IMAGE=<ref> runs that image as is, without our build.

if [[ "${EUID}" -ne 0 && "${ALLOW_NON_ROOT:-}" != "true" ]]; then
  echo "Run as root: sudo bash $0"
  exit 1
fi

DOCKGE_DIR="${DOCKGE_DIR:-/opt/dockge}"
DOCKGE_STACKS_DIR="${DOCKGE_STACKS_DIR:-/opt/dockge/stacks}"
DOCKGE_DATA_DIR="${DOCKGE_DATA_DIR:-${DOCKGE_DIR}/data}"
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
LOCAL_IMAGE="infra-vps-dockge:local"
DOCKGE_IMAGE="${DOCKGE_IMAGE:-${LOCAL_IMAGE}}"
DOCKGE_BIND_ADDRESS="${DOCKGE_BIND_ADDRESS:-127.0.0.1}"
DOCKGE_PORT="${DOCKGE_PORT:-5001}"
DOCKGE_USER="${DOCKGE_USER:-deploy}"
COMPOSE_FILE="${DOCKGE_DIR}/compose.yaml"

if ! id -u "${DOCKGE_USER}" >/dev/null 2>&1; then
  echo "User not found: ${DOCKGE_USER}"
  exit 1
fi

DOCKGE_UID="$(id -u "${DOCKGE_USER}")"
DOCKGE_GID="$(id -g "${DOCKGE_USER}")"

if [[ "${DOCKGE_IMAGE}" == "${LOCAL_IMAGE}" ]]; then
  echo "Building ${LOCAL_IMAGE} (upstream image + security fixes)"
  docker build --pull --build-arg SECURITY_REFRESH="$(date -u +%Y%m%dT%H%M%S)" \
    -t "${LOCAL_IMAGE}" "${REPO_ROOT}/dockge/image"
  pull_policy="never"
else
  pull_policy="missing"
fi

mkdir -p "${DOCKGE_DIR}"
mkdir -p "${DOCKGE_STACKS_DIR}"
mkdir -p "${DOCKGE_DATA_DIR}"

cat > "${COMPOSE_FILE}" <<EOF
# Generated by infra-vps/scripts/007-install-dockge.sh — edit that, not this file.
services:
  dockge:
    image: ${DOCKGE_IMAGE}
    pull_policy: ${pull_policy}
    restart: unless-stopped
    labels:
      # security report auto-fix: rebuild = the infra deploy workflow
      infra-vps.fix: github-workflow
      infra-vps.fix.repo: IavnFGV/infra-vps
      infra-vps.fix.workflow: deploy.yml
    ports:
      - ${DOCKGE_BIND_ADDRESS}:${DOCKGE_PORT}:5001
    volumes:
      - /var/run/docker.sock:/var/run/docker.sock
      - ${DOCKGE_DATA_DIR}:/app/data
      - ${DOCKGE_STACKS_DIR}:${DOCKGE_STACKS_DIR}
    environment:
      - DOCKGE_STACKS_DIR=${DOCKGE_STACKS_DIR}
      - PUID=${DOCKGE_UID}
      - PGID=${DOCKGE_GID}
EOF

chown -R "${DOCKGE_USER}:${DOCKGE_USER}" "${DOCKGE_DIR}"

(
  cd "${DOCKGE_DIR}"
  docker compose up -d
)

echo "Dockge installed."
echo "Compose file: ${COMPOSE_FILE}"
echo "Stacks dir: ${DOCKGE_STACKS_DIR}"
echo "Data dir: ${DOCKGE_DATA_DIR}"
echo "Listen address: ${DOCKGE_BIND_ADDRESS}:${DOCKGE_PORT}"
if [[ "${DOCKGE_BIND_ADDRESS}" == "127.0.0.1" ]]; then
  echo "Dockge is only reachable from the server itself by default."
fi
